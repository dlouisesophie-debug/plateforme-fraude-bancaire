-- -------------------------------------------------------------------------
-- users : comptes de la plateforme (modèle AbstractUser de Django + rôle).
-- Connexion par nom d'utilisateur (username, unique) ; l'e-mail n'est pas unique.
-- Mot de passe : empreinte PBKDF2-SHA256 (hacheur par défaut de Django), jamais en clair.
-- -------------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    password        VARCHAR(128)  NOT NULL,
    last_login      TIMESTAMPTZ,
    is_superuser    BOOLEAN       NOT NULL,
    username        VARCHAR(150)  NOT NULL UNIQUE,
    first_name      VARCHAR(150)  NOT NULL,
    last_name       VARCHAR(150)  NOT NULL,
    email           VARCHAR(254)  NOT NULL,
    is_staff        BOOLEAN       NOT NULL,
    is_active       BOOLEAN       NOT NULL,
    date_joined     TIMESTAMPTZ   NOT NULL,
    role            VARCHAR(20)   NOT NULL   -- admin | analyst | agent
);
CREATE INDEX users_role_0ace22_idx ON users (role);
-- Index ajoutés par Django sur les colonnes texte uniques, pour les recherches LIKE.
CREATE INDEX users_username_e8658fc8_like ON users (username varchar_pattern_ops);

-- -------------------------------------------------------------------------
-- transactions : opérations saisies par un agent (ou un administrateur).
-- Les colonnes customer_* décrivent le client au moment de la transaction :
-- ce sont des variables du modèle ML, recopiées à chaque saisie (pas de table
-- client). Conséquence assumée : le schéma n'est pas en 3e forme normale.
-- -------------------------------------------------------------------------
CREATE TABLE transactions (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id            VARCHAR(50)    NOT NULL UNIQUE,   -- identifiant métier
    amount                    NUMERIC(12,2)  NOT NULL,          -- FCFA ; unité du simulateur PaySim
                                                                -- si canal mobile_money avec operation_type
    merchant                  VARCHAR(255)   NOT NULL,
    device                    VARCHAR(100)   NOT NULL,
    location                  VARCHAR(255)   NOT NULL,
    channel                   VARCHAR(30)    NOT NULL,   -- card | mobile_money | transfer | online
    operation_type            VARCHAR(20)    NOT NULL DEFAULT '',
                                  -- mobile money : cash_in | cash_out | transfer | payment | debit ; '' sinon
    "timestamp"               TIMESTAMPTZ    NOT NULL,   -- date et heure de l'opération
    status                    VARCHAR(20)    NOT NULL,   -- pending | legitimate | fraudulent | under_review
    created_at                TIMESTAMPTZ    NOT NULL,   -- date de saisie
    created_by_id             BIGINT,                    -- FK users, ON DELETE SET NULL (Django)
    category                  VARCHAR(100)   NOT NULL,
    customer_gender           VARCHAR(1)     NOT NULL,   -- F | M | '' ; plus utilisé par le modèle carte v2
    customer_birth_date       DATE,
    customer_city             VARCHAR(150)   NOT NULL,
    customer_region           VARCHAR(100)   NOT NULL,
    customer_city_population  INTEGER CHECK (customer_city_population >= 0),
    customer_profession       VARCHAR(150)   NOT NULL,
    customer_latitude         DOUBLE PRECISION,
    customer_longitude        DOUBLE PRECISION,
    merchant_latitude         DOUBLE PRECISION,
    merchant_longitude        DOUBLE PRECISION,
    CONSTRAINT transactions_created_by_id_fk_users_id
        FOREIGN KEY (created_by_id) REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX transaction_channel_d225f9_idx ON transactions (channel);
CREATE INDEX transaction_status_505a2f_idx  ON transactions (status);
CREATE INDEX transaction_timesta_07633a_idx ON transactions ("timestamp");
CREATE INDEX transactions_created_by_id_bde7c54f ON transactions (created_by_id);
CREATE INDEX transactions_transaction_id_51252f6b_like ON transactions (transaction_id varchar_pattern_ops);

-- -------------------------------------------------------------------------
-- ml_models : versions des modèles ML enregistrées (CDC 5.3 / 5.5).
-- Un seul modèle actif par famille (index unique partiel ci-dessous).
-- Métriques mesurées sur le jeu de test ; le seuil de décision est dans le
-- fichier .joblib (artifact_path), pas dans cette table.
-- -------------------------------------------------------------------------
CREATE TABLE ml_models (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version          VARCHAR(50)   NOT NULL UNIQUE,
    famille          VARCHAR(20)   NOT NULL DEFAULT 'carte',   -- carte | mobile_money
    algorithm        VARCHAR(50)   NOT NULL,   -- logistic_regression | random_forest | xgboost
    precision_score  DOUBLE PRECISION,         -- 0 à 1 (validé par Django)
    recall_score     DOUBLE PRECISION,
    f1_score         DOUBLE PRECISION,
    auc_roc          DOUBLE PRECISION,
    trained_at       TIMESTAMPTZ   NOT NULL,   -- date d'entraînement lue dans le fichier
    is_active        BOOLEAN       NOT NULL,
    artifact_path    VARCHAR(255)  NOT NULL    -- fichier .joblib (relatif à ML_MODELS_DIR)
);
CREATE UNIQUE INDEX single_active_model_per_family ON ml_models (famille) WHERE is_active;
CREATE INDEX ml_models_version_72f33f9c_like ON ml_models (version varchar_pattern_ops);

-- -------------------------------------------------------------------------
-- predictions : score d'une transaction (au plus une prédiction par transaction ;
-- une transaction non scorée, statut pending, n'en a pas).
-- -------------------------------------------------------------------------
CREATE TABLE predictions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id      BIGINT  NOT NULL UNIQUE,   -- FK transactions, ON DELETE CASCADE (Django)
    ml_model_id         BIGINT  NOT NULL,          -- FK ml_models, ON DELETE PROTECT (Django)
    fraud_probability   DOUBLE PRECISION NOT NULL, -- 0 à 1
    prediction          BOOLEAN NOT NULL,          -- TRUE = frauduleuse (score >= seuil)
    decision_threshold  DOUBLE PRECISION,          -- seuil du modèle appliqué (NULL avant le 23/11/2026)
    prediction_date     TIMESTAMPTZ NOT NULL,
    CONSTRAINT predictions_transaction_id_fk_transactions_id
        FOREIGN KEY (transaction_id) REFERENCES transactions (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT predictions_ml_model_id_fk_ml_models_id
        FOREIGN KEY (ml_model_id) REFERENCES ml_models (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX predictions_fraud_p_d82679_idx ON predictions (fraud_probability);
CREATE INDEX predictions_ml_model_id_ae4b88b3 ON predictions (ml_model_id);

-- -------------------------------------------------------------------------
-- alerts : créée automatiquement quand le modèle prédit une fraude
-- (au plus une alerte par prédiction), puis traitée par un analyste.
-- -------------------------------------------------------------------------
CREATE TABLE alerts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prediction_id   BIGINT       NOT NULL UNIQUE,   -- FK predictions, ON DELETE CASCADE (Django)
    status          VARCHAR(20)  NOT NULL,   -- open | confirmed | rejected | resolved
    severity        VARCHAR(10)  NOT NULL,   -- low | medium | high | critical (selon le score)
    comment         TEXT         NOT NULL,   -- annotation de l'analyste ('' par défaut)
    created_at      TIMESTAMPTZ  NOT NULL,
    resolved_at     TIMESTAMPTZ,
    assigned_to_id  BIGINT,                  -- FK users, ON DELETE SET NULL (Django)
    CONSTRAINT alerts_prediction_id_fk_predictions_id
        FOREIGN KEY (prediction_id) REFERENCES predictions (id) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT alerts_assigned_to_id_fk_users_id
        FOREIGN KEY (assigned_to_id) REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX alerts_status_0e4dc1_idx  ON alerts (status);
CREATE INDEX alerts_severit_362484_idx ON alerts (severity);
CREATE INDEX alerts_assigned_to_id_959abf03 ON alerts (assigned_to_id);

-- -------------------------------------------------------------------------
-- reports : rapports PDF / CSV générés (le fichier est sur disque, file_path).
-- -------------------------------------------------------------------------
CREATE TABLE reports (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(255) NOT NULL,
    type             VARCHAR(10)  NOT NULL,   -- pdf | csv
    period_start     DATE,
    period_end       DATE,
    file_path        VARCHAR(255) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL,
    generated_by_id  BIGINT,                  -- FK users, ON DELETE SET NULL (Django)
    CONSTRAINT reports_generated_by_id_fk_users_id
        FOREIGN KEY (generated_by_id) REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX reports_generated_by_id_18d9bf61 ON reports (generated_by_id);

-- -------------------------------------------------------------------------
-- audit_logs : journal d'audit. Écritures sur l'API (POST, PUT, PATCH, DELETE),
-- lectures sensibles (fiche transaction, export CSV, téléchargement de rapport),
-- connexions et gestion des comptes.
-- -------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT,                   -- FK users, ON DELETE SET NULL (Django) ; NULL = connexion échouée
    action      VARCHAR(100) NOT NULL,    -- ex. LOGIN_SUCCESS, "PATCH /api/alerts/12/"
    ip_address  INET,
    details     JSONB,                    -- code HTTP, filtres d'un export...
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT audit_logs_user_id_fk_users_id
        FOREIGN KEY (user_id) REFERENCES users (id) DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX audit_logs_action_31f574_idx  ON audit_logs (action);
CREATE INDEX audit_logs_created_262184_idx ON audit_logs (created_at);
CREATE INDEX audit_logs_user_id_752b0e2b   ON audit_logs (user_id);
